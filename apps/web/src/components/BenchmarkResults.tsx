'use client';

import { useCallback, useEffect, useRef, useState } from 'react';
import { BenchmarkComparison, BenchmarkStoredScore } from '../lib/benchmark';
import {
  benchmarkResultExport,
  benchmarkResultsAccessInvalid,
  loadBenchmarkResults,
  measuredDuration,
  recordedCost,
} from '../lib/benchmark-results';
import BenchmarkCellEvidence from './BenchmarkCellEvidence';
import styles from './BenchmarkResults.module.css';

export function BenchmarkResultDashboard({
  comparison,
  score: loadedScore,
  base,
  busy,
  loaded,
  error,
  refresh,
  accessInvalid = false,
}: {
  comparison: BenchmarkComparison;
  score: BenchmarkStoredScore | null;
  base: string;
  busy: boolean;
  loaded: boolean;
  error: string;
  refresh: () => void;
  accessInvalid?: boolean;
}) {
  const score = accessInvalid ? null : loadedScore;
  const cells = accessInvalid ? [] : comparison.cells;
  const models = score?.projection.models || [];
  const captured = cells.filter(
    (cell) => cell.state === 'completed' || cell.state === 'model_failed',
  ).length;
  const fictional = comparison.origin === 'original_synthetic_fixture';
  return (
    <section className={styles.results} aria-label="Comparison results">
      <header className={styles.header}>
        <div>
          <p className={styles.eyebrow}>BENCHMARK / STORED RESULTS</p>
          <h2>Results and evidence</h2>
          <p>Exact observations, preserved revisions and the evidence behind every result.</p>
        </div>
        <button type="button" disabled={busy} onClick={refresh}>
          {busy ? 'Refreshing stored results…' : 'Refresh stored results'}
        </button>
      </header>

      <aside className={styles.origin} aria-label="Result provenance">
        <strong>{fictional ? 'Fictional software run' : 'Benchmark evidence'}</strong>
        <span>
          {fictional
            ? 'Original synthetic fixtures · Not a measurement of live model performance'
            : 'Recorded origin: ' + comparison.origin}
        </span>
      </aside>
      {error && (
        <p className={styles.error} role="alert">
          {error}{' '}
          {score
            ? 'Previously loaded revision remains below; refresh to verify current state.'
            : ''}
        </p>
      )}
      {!loaded && !error && <p role="status">Loading the stored score revision…</p>}

      <div className={styles.summary}>
        <article>
          <span>Run state</span>
          <strong>
            {accessInvalid ? 'Access unavailable' : comparison.state.replaceAll('_', ' ')}
          </strong>
        </article>
        <article>
          <span>Finished cells</span>
          <strong>
            {captured} <small>/ {comparison.planned_cells}</small>
          </strong>
        </article>
        <article>
          <span>Score revision</span>
          <strong>
            {score ? `Revision ${score.revision}` : loaded ? 'Not published' : 'Checking…'}
          </strong>
        </article>
        <article>
          <span>Independent review</span>
          <strong>
            {score
              ? score.review_state.replaceAll('_', ' ')
              : loaded
                ? 'No score revision'
                : 'Checking…'}
          </strong>
          <small>{score ? `${score.reviews} recorded decisions` : 'No approval inferred'}</small>
        </article>
      </div>

      {!score ? (
        loaded && (
          <div className={styles.empty}>
            <h3>No stored score revision yet</h3>
            <p>
              Execution must capture and evaluate actual outputs before results are published.
              Queued, unknown and invalid trials never become model zeroes.
            </p>
            <p>
              Reopen this run or refresh after new evidence is recorded. No scores are generated by
              this page.
            </p>
            {comparison.model_slots && comparison.model_slots.length > 0 && (
              <ul aria-label="Frozen model bindings">
                {comparison.model_slots.map((model) => (
                  <li key={model.slot}>
                    Slot {model.slot + 1}: {model.provider} · {model.model_id}
                  </li>
                ))}
              </ul>
            )}
          </div>
        )
      ) : (
        <>
          <div className={styles.sectionTitle}>
            <div>
              <h3>Model observations</h3>
              <p>Shown in frozen slot order. No ranking or winner is inferred.</p>
            </div>
            <span className={styles.badge}>
              {score.projection.complete ? 'Reviewed publication' : 'Primary pending'}
            </span>
          </div>
          <div className={styles.models}>
            {models.map((model) => (
              <article
                key={model.slot}
                className={styles.model}
                aria-label={`Model slot ${model.slot + 1} results`}
              >
                <div className={styles.modelHeading}>
                  <span>MODEL SLOT {model.slot + 1}</span>
                  <span>{model.provider}</span>
                </div>
                <h4>{model.model_id}</h4>
                <div className={styles.primary}>
                  <span>Reviewed primary</span>
                  {model.primary ? (
                    <>
                      <strong>
                        {model.primary.earned_points}
                        <small> / {model.primary.possible_points}</small>
                      </strong>
                      <span>{model.primary.percent}%</span>
                    </>
                  ) : (
                    <>
                      <strong className={styles.pending}>Unavailable</strong>
                      <span>
                        {model.score_complete
                          ? 'Required independent review remains pending.'
                          : 'Complete, valid evidence and required review are not yet available.'}
                      </span>
                    </>
                  )}
                </div>
                <div className={styles.diagnostic}>
                  <span>Unranked diagnostic mean</span>
                  <strong>
                    {model.diagnostic.complete_repetition_mean
                      ? `${model.diagnostic.complete_repetition_mean.earned_points} / ${model.diagnostic.complete_repetition_mean.possible_points}`
                      : 'Unavailable'}
                  </strong>
                  <small>
                    {model.diagnostic.complete_repetition_mean
                      ? `${model.diagnostic.complete_repetition_mean.percent}% · complete suite repetitions only`
                      : 'No complete suite repetition has been scored.'}
                  </small>
                </div>
                <dl className={styles.metrics}>
                  <div>
                    <dt>Scored cells</dt>
                    <dd>
                      {model.scored} / {model.planned}
                    </dd>
                  </div>
                  <div>
                    <dt>Complete repetitions</dt>
                    <dd>{model.diagnostic.complete_repetitions.length} / 2</dd>
                  </div>
                  <div>
                    <dt>Median measured duration</dt>
                    <dd>
                      {measuredDuration(model.duration.median_ms)}
                      <small>{model.duration.samples} samples</small>
                    </dd>
                  </div>
                  <div>
                    <dt>Recorded total cost</dt>
                    <dd>
                      {recordedCost(model.cost.combined_micro_usd)}
                      <small>{model.cost.status}</small>
                    </dd>
                  </div>
                </dl>
                <details className={styles.detail}>
                  <summary>Repetition and usage detail</summary>
                  {model.diagnostic.complete_repetitions.length ? (
                    <ul>
                      {model.diagnostic.complete_repetitions.map((repetition) => (
                        <li key={repetition.repetition}>
                          Repetition {repetition.repetition + 1}: {repetition.earned_points} /{' '}
                          {repetition.possible_points} ({repetition.percent}%)
                        </li>
                      ))}
                    </ul>
                  ) : (
                    <p>No complete repetition is available.</p>
                  )}
                  <p>
                    Observed criterion points: {model.diagnostic.earned_points} /{' '}
                    {model.diagnostic.possible_points}. This partial total is not a comparable
                    primary score.
                  </p>
                  <p>
                    Candidate cost: {recordedCost(model.cost.candidate_micro_usd)} · Judge cost:{' '}
                    {recordedCost(model.cost.judge_micro_usd)}. Missing usage remains unknown.
                  </p>
                </details>
              </article>
            ))}
          </div>
          <p className={styles.explanation}>
            The primary uses the frozen 81-point suite and requires complete valid observations plus
            the assigned reviews. Diagnostics retain actual observations without replacing missing
            cells or granting approval.
          </p>
        </>
      )}

      <div className={styles.sectionTitle}>
        <div>
          <h3>Cell evidence</h3>
          <p>Inspect the actual task, repetition and captured output behind a result.</p>
        </div>
      </div>
      <div className={styles.cellList}>
        {cells.map((cell) => {
          const binding = comparison.model_slots?.find((item) => item.slot === cell.slot);
          return (
            <details className={styles.cell} key={cell.cell_id}>
              <summary>
                <span>
                  {comparison.task_labels?.[cell.task_revision_id] || cell.task_revision_id}
                </span>
                <span>{binding?.model_id || `Model slot ${cell.slot + 1}`}</span>
                <span>Repetition {cell.repetition + 1}</span>
                <span className={styles.cellState}>{cell.state.replaceAll('_', ' ')}</span>
              </summary>
              <div className={styles.cellBody}>
                <p>
                  Validity: {cell.validity || 'Not established'} ·{' '}
                  {cell.reconciled
                    ? 'Operator reconciliation recorded'
                    : 'No operator reconciliation recorded'}
                </p>
                <p className={styles.identifier}>Cell: {cell.cell_id}</p>
                <BenchmarkCellEvidence
                  base={base}
                  runId={comparison.run_id}
                  cellId={cell.cell_id}
                />
              </div>
            </details>
          );
        })}
        {!cells.length && (
          <p>
            {accessInvalid
              ? 'Evidence is unavailable until current access and policy are verified.'
              : 'No cells were returned for this run.'}
          </p>
        )}
      </div>

      <footer className={styles.footer}>
        <div>
          <h3>Revision and exports</h3>
          <p>
            Downloads bind the revision shown here. The server rechecks current project access,
            source rights and private evidence duties.
          </p>
        </div>
        {score && (
          <nav className={styles.exports} aria-label="Stored result exports">
            {(
              [
                ['json', 'JSON'],
                ['csv', 'Redacted CSV'],
                ['report', 'Redacted report'],
                ['atif', 'Harbor trajectories'],
              ] as const
            ).map(([format, label]) => (
              <a
                key={format}
                href={benchmarkResultExport(
                  base,
                  comparison.run_id,
                  score.score_revision_id,
                  format,
                )}
              >
                {label} ↗
              </a>
            ))}
          </nav>
        )}
        <details className={styles.detail}>
          <summary>Exact stored provenance</summary>
          <dl className={styles.provenance}>
            <div>
              <dt>Run</dt>
              <dd>{comparison.run_id}</dd>
            </div>
            <div>
              <dt>Protocol revision</dt>
              <dd>{comparison.protocol_revision_id}</dd>
            </div>
            <div>
              <dt>Protocol SHA-256</dt>
              <dd>{comparison.subject_sha256}</dd>
            </div>
            <div>
              <dt>Origin</dt>
              <dd>{score?.projection.origin || comparison.origin}</dd>
            </div>
            {score && (
              <>
                <div>
                  <dt>Score revision</dt>
                  <dd>{score.score_revision_id}</dd>
                </div>
                <div>
                  <dt>Projection SHA-256</dt>
                  <dd>{score.projection_sha256}</dd>
                </div>
              </>
            )}
          </dl>
        </details>
      </footer>
    </section>
  );
}

export default function BenchmarkResults({
  comparison,
  base,
  changed,
}: {
  comparison: BenchmarkComparison;
  base: string;
  changed: (comparison: BenchmarkComparison) => void;
}) {
  const [current, setCurrent] = useState(comparison);
  const [score, setScore] = useState<BenchmarkStoredScore | null>(null);
  const [busy, setBusy] = useState(false),
    [loaded, setLoaded] = useState(false),
    [error, setError] = useState('');
  const generation = useRef(0);
  const currentRef = useRef(comparison);
  const [accessInvalid, setAccessInvalid] = useState(false);
  const refresh = useCallback(async () => {
    const request = ++generation.current;
    setBusy(true);
    setError('');
    try {
      const value = await loadBenchmarkResults(base, comparison.run_id);
      if (request !== generation.current) return;
      setCurrent(value.comparison);
      currentRef.current = value.comparison;
      setScore(value.score);
      changed(value.comparison);
      setLoaded(true);
      setAccessInvalid(false);
    } catch (failure) {
      if (request === generation.current) {
        setError((failure as Error).message);
        if (benchmarkResultsAccessInvalid(failure)) {
          setScore(null);
          setLoaded(false);
          setAccessInvalid(true);
          const unavailable = { ...currentRef.current, cells: [], scorecard: null };
          setCurrent(unavailable);
          currentRef.current = unavailable;
          changed(unavailable);
        }
      }
    } finally {
      if (request === generation.current) setBusy(false);
    }
  }, [base, comparison.run_id, changed]);
  useEffect(() => {
    void refresh();
    return () => {
      generation.current++;
    };
  }, [refresh, comparison.checkpoint_event_seq]);
  return (
    <BenchmarkResultDashboard
      comparison={current}
      score={score}
      base={base}
      busy={busy}
      loaded={loaded}
      error={error}
      refresh={() => void refresh()}
      accessInvalid={accessInvalid}
    />
  );
}

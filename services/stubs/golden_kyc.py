def evaluator_binding(criterion, skill_group, evidence_type, rule):
    """Studio S7 binding for one criterion, sent through A-06. Known cases carry their evidence inline so the RL
    Gym can run allowed / disallowed / missing-evidence tests without reading candidate output."""
    allowed_case = _make_case("individual", 1)
    disallowed_case = _make_case("teen_joint", 3)
    missing_case = _make_case("custodial", 5)

    def good(case):
        ref = case["reference"]
        return {
            "tool_events": [
                {"tool": "application.read", "ok": True},
                *[{"tool": "identity.check", "ok": True} for _ in range(ref["party_count"])],
                *[{"tool": "screening.check", "ok": True} for _ in range(ref["party_count"])],
                {"tool": "agreements.check", "ok": True},
                {"tool": "state_rules.lookup", "ok": True},
            ],
            "final_output": {
                **{k: ref[k] for k in ref},
                "findings": [{"text": "documented", "evidence_ref": "doc-1"}],
            },
        }

    def bad(case):
        bundle = good(case)
        ref = case["reference"]
        kind = rule["kind"]
        if kind in ("tool_called",):
            bundle["tool_events"] = [e for e in bundle["tool_events"] if e["tool"] != rule["tool"]]
        elif kind == "tool_not_called":
            bundle["tool_events"].append({"tool": rule["tool"], "ok": True})
        elif kind == "output_nonempty":
            bundle["final_output"][rule["field"]] = []
        elif kind == "output_set_equals":
            bundle["final_output"][rule["field"]] = list(ref[rule["reference"]])[:1] + [
                "unexpected"
            ]
        else:
            value = ref[rule["reference"]]
            bundle["final_output"][rule["field"]] = (
                (not value)
                if isinstance(value, bool)
                else (value + 1 if isinstance(value, int) else f"not-{value}")
            )
        return bundle

    missing = good(missing_case)
    missing.pop(evidence_type)
    return {
        "schema": "rlgym.evaluator-create.v1",
        "id": f"golden-kyc:{criterion}",
        "template": {"id": TEMPLATE_ID, "key": TEMPLATE_KEY, "version": TEMPLATE_VERSION},
        "criterion": criterion,
        "capability": "golden-kyc",
        "skill_group": skill_group,
        "weight": 5,
        "framework": LOCAL_PYTHON_FRAMEWORK,
        "evidence_type": evidence_type,
        "verdict_vocabulary": ["pass", "partial", "fail", "blocked"],
        "config": {"evidence": evidence_type, "rules": [rule]},
        "known_cases": {
            "allowed": {
                "case_id": allowed_case["case_id"],
                "evidence": good(allowed_case),
                "reference": allowed_case["reference"],
                "expect": "pass",
            },
            "disallowed": {
                "case_id": disallowed_case["case_id"],
                "evidence": bad(disallowed_case),
                "reference": disallowed_case["reference"],
                "expect": "fail",
            },
            "missing_evidence": {
                "case_id": missing_case["case_id"],
                "evidence": missing,
                "reference": missing_case["reference"],
                "expect": "blocked",
            },
        },
    }



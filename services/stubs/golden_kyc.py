def template(version=TEMPLATE_VERSION):
    if version not in (TEMPLATE_VERSION, GATED_VERSION, BLOCKS_VERSION, EDGES_VERSION, ZEN_VERSION):
        raise ValueError(f"unknown Golden KYC version {version}")
    blocks = version >= BLOCKS_VERSION
    doc = {
        "template_id": TEMPLATE_ID,
        "key": TEMPLATE_KEY,
        "version": version,
        "name": f"Golden KYC V{version}",
        "mode": "single_agent",
        "pass_mark": PASS_MARK,
        "studio_release": {
            TEMPLATE_VERSION: "rel-0412",
            GATED_VERSION: "rel-0455",
            BLOCKS_VERSION: "rel-0461",
            EDGES_VERSION: "rel-0462",
        }.get(version, "rel-0463"),
        "bindings": [
            {
                "alias": ALIAS,
                "contract_id": CONTRACT,
                "rule": {
                    "kind": "same_data",
                    "seed_family": SNAPSHOT_SEED_FAMILY if blocks else SEED_FAMILY,
                },
            }
        ],
        "criteria": [
            {
                "criterion_id": c,
                "capability": "golden-kyc",
                "skill_group": g,
                "weight": 5,
                "is_gate": version >= GATED_VERSION and c in GATES,
                "configuration_id": f"{BLOCK_CAPABILITY}:{c}"
                if blocks and c in VERIFIER_BLOCKS
                else f"golden-kyc:{c}",
                "evidence_type": "snapshots" if blocks and c in VERIFIER_BLOCKS else e,
                "verdict_vocabulary": ["pass", "partial", "fail", "blocked"],
                **(
                    {"verifier_blocks": VERIFIER_BLOCKS[c]}
                    if blocks and c in VERIFIER_BLOCKS
                    else {}
                ),
            }
            for c, g, e, _ in CRITERIA
        ],
        "workflow": WORKFLOW,
        "case_dimensions": {
            "application_type": PRODUCTS,
            "completeness": COMPLETENESS,
            "edge_cases": EDGE_CASES,
        },
        "forge_template_id": FORGE_TEMPLATE_ID,
        "forge_version": {
            TEMPLATE_VERSION: FORGE_VERSION,
            GATED_VERSION: 4,
            BLOCKS_VERSION: 5,
            EDGES_VERSION: 6,
        }.get(version, 7),
    }
    if blocks:
        doc["expected_values_from"] = "case_reference"
        doc["failure_taxonomy"] = FAILURE_TAXONOMY
    if version >= EDGES_VERSION:
        doc["edge_cases"] = S4_EDGE_CASES
        doc["slice_lists"] = SLICE_LISTS
    if version >= ZEN_VERSION:
        decision = next(c for c in doc["criteria"] if c["criterion_id"] == "decision")
        decision["verifier_blocks"] = [*decision["verifier_blocks"], ZEN_BLOCK]
        doc["verifier_files"] = {ZEN_RULES_SHA256: ZEN_RULES}
    doc["spec_sha256"] = sha(
        {k: v for k, v in doc.items() if k not in ("forge_template_id", "forge_version")}
    )
    doc["template_sha256"] = sha(doc)
    return doc


def forge_tasks(
    export_id, corrections=None, template_version=TEMPLATE_VERSION, project_id=FORGE_PROJECT_ID
):
    """40 authored KYC tasks: 10 per product (5 complete, 4 incomplete, 1 edge-case focus). `corrections` maps
    task_id → {revision, sme_batch_id, note} for re-exports after SME review."""
    corrections = corrections or {}
    out = []
    n = 0
    for product in PRODUCTS:
        plan = ["complete"] * 5 + ["incomplete"] * 4 + ["edge"]
        for kind in plan:
            n += 1
            task_id = f"task-kyc-{n:04d}"
            corr = corrections.get(task_id, {})
            revision = corr.get("revision", 1)
            edge = []
            completeness = "incomplete" if kind == "incomplete" else "complete"
            if kind == "edge":
                edge = (
                    ["minor_without_tin"]
                    if product in ("teen_joint", "custodial")
                    else ["screening_hit"]
                )
            selector = {
                "application_type": product,
                "completeness": completeness,
                "edge_cases": edge,
            }
            package = {
                "schema": "praxis.authored-task-package.v1",
                "task_id": task_id,
                "revision": revision,
                "actor": {
                    "assignment": f"Review this {product.replace('_', ' ')} account application under Golden KYC V{template_version} "
                    "and return a decision with findings."
                    + (
                        " Ask for missing information with information.request (type) and refer sanctions concerns "
                        "with specialist.refer (specialty)."
                        if template_version >= BLOCKS_VERSION
                        else ""
                    ),
                    "inputs": "The application record for one synthetic case (read with application.read).",
                    "tools": TOOLS[:-2]
                    + ["recommend", "escalate"]
                    + (
                        ["information.request", "specialist.refer"]
                        if template_version >= BLOCKS_VERSION
                        else []
                    ),
                    "output_contract": [
                        "party_count",
                        "decision",
                        "next_action",
                        "findings",
                        "account_type",
                        "roles",
                        "eligible",
                        "authorized_signer",
                        "party_separation",
                        "exceptions",
                        "resolution",
                        "state",
                        "review_due_days",
                        "instrument",
                    ],
                    "note": corr.get("note"),
                },
                "private": {
                    "rubric": "golden-kyc-rubric-v1",
                    "criteria": 20,
                    "points_each": 5,
                    "pass_mark": PASS_MARK,
                    "expected": "per case: reference_answers in the environment seed (never shown to the agent)",
                    "grading_notes": corr.get(
                        "grading_note", "Score each S7 criterion from the sealed evidence."
                    ),
                    # 2.12 slice tags (S1 lists), private: V11 and later only, so earlier packages keep their hashes.
                    **(
                        {
                            "complexity": {
                                "complete": "single_step",
                                "incomplete": "multi_hop",
                                "edge": "judgement",
                            }[kind],
                            "archetype": ARCHETYPE_FOR.get((edge or [None])[0], "standard"),
                        }
                        if template_version >= EDGES_VERSION
                        else {}
                    ),
                },
            }
            out.append(
                {
                    "schema": "praxis.authored-task-export.v1",
                    "task_id": task_id,
                    "revision": revision,
                    "title": f"{product.replace('_', ' ').title()} · {kind.replace('edge', 'edge case')} · {n:02d}",
                    **(
                        {
                            "corrects_revision": revision - 1,
                            "sme_batch_id": corr.get("sme_batch_id"),
                        }
                        if revision > 1
                        else {}
                    ),
                    "package": package,
                    "package_sha256": sha(package),
                    "package_ref": f"stub://forge/exports/{project_id}/{export_id}/{task_id}-r{revision}.json",
                    "case_selector": selector,
                }
            )
    return out


def project_export(
    export_id, reason, corrections=None, extra=None, project_id=FORGE_PROJECT_ID, linked=None
):
    """`linked` = {project_name, template: {id, version, spec_sha256, forge_template_id, forge_version}} exports the
    same 40 Golden KYC tasks for a template another registry released (the local Studio link); otherwise one of
    PROJECTS (V8 KYC November, V9 KYC December)."""
    if linked:
        template_ref = linked["template"]
        version = int(template_ref["version"])
        name = linked.get("project_name") or project_id
        tasks = forge_tasks(export_id, corrections, version, project_id)
        for task in tasks:
            # Packages are bound to this project and template so they never collide with another project's tasks.
            task["package"]["actor"]["project"] = project_id
            # The tools are the environment version's own declared operations (Studio's), not the stub's list.
            task["package"]["actor"].pop("tools", None)
            task["package"]["private"]["template"] = {
                k: template_ref[k] for k in ("id", "version", "spec_sha256")
            }
            task["package_sha256"] = sha(task["package"])
    else:
        project = PROJECTS[project_id]
        t = template(project["template_version"])
        tasks = forge_tasks(export_id, corrections, project["template_version"], project_id)
        name = project["name"]
        template_ref = {
            "id": TEMPLATE_ID,
            "version": project["template_version"],
            "spec_sha256": t["spec_sha256"],
            "forge_template_id": FORGE_TEMPLATE_ID,
            "forge_version": project["forge_version"],
        }
    body = {
        "schema": "rlgym.project-export.v1",
        "project_id": project_id,
        "project_name": name,
        "template": {
            "id": template_ref["id"],
            "version": int(template_ref["version"]),
            "spec_sha256": template_ref["spec_sha256"],
            "forge_template_id": template_ref.get("forge_template_id", FORGE_TEMPLATE_ID),
            "forge_version": int(template_ref.get("forge_version", 1)),
        },
        "project_config": {"mode": "single_agent"},
        "export_id": export_id,
        "reason": reason,
        "tasks": [{k: v for k, v in task.items() if k != "package"} for task in tasks],
        **(extra or {}),
    }
    body["export_sha256"] = sha(body)
    return body, {task["package_sha256"]: task["package"] for task in tasks}


def image_seed(rows):
    """The environment image seed: actor-visible records plus environment facts the tools answer from (which party
    a synthetic screening list matches). Reference answers are not part of the image; the scorer gets them separately."""
    lines = []
    for c in rows:
        hits = ["P1"] if "screening_hit" in c["edge_cases"] else []
        lines.append(
            canonical(
                {
                    "case_id": c["case_id"],
                    "application_type": c["application_type"],
                    "completeness": c["completeness"],
                    "edge_cases": c["edge_cases"],
                    "actor": c["actor"],
                    "env": {"screening_hits": hits},
                }
            )
        )
    return "\n".join(lines) + "\n"

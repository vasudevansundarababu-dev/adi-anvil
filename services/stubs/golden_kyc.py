def _make_case(product, n, seed=SEED):
    """One synthetic case. Deterministic per (product, n) so v2's 20 cases are kept unchanged in v3."""
    rng = random.Random(f"{seed}:{product}:{n}")
    parties = 1 if product == "individual" else 2
    edge = []
    if product in ("teen_joint", "custodial") and rng.random() < 0.18:
        edge.append("minor_without_tin")
    if rng.random() < 0.12:
        edge.append("expired_id")
    if rng.random() < 0.08:
        edge.append("screening_hit")
    if rng.random() < 0.10:
        edge.append("address_mismatch")
    completeness = "incomplete" if rng.random() < 0.3 else "complete"
    state = rng.choice(STATES)
    exceptions = sorted(e for e in edge if e in ("expired_id", "address_mismatch"))
    if "screening_hit" in edge or "minor_without_tin" in edge:
        decision, next_action, resolution = (
            "escalate",
            "escalate_to_compliance",
            "pending_compliance",
        )
    elif completeness == "incomplete" or exceptions:
        decision, next_action, resolution = (
            "request_documents",
            "request_missing_documents",
            "pending_customer",
        )
    else:
        decision, next_action, resolution = "approve", "open_account", "approved"
    roles = {
        "individual": ["owner"],
        "adult_joint": ["owner", "joint_owner"],
        "teen_joint": ["owner", "minor_joint_owner"],
        "custodial": ["custodian", "beneficiary"],
    }[product]
    applicants = []
    for i, role in enumerate(roles[:parties]):
        applicants.append(
            {
                "party": f"P{i + 1}",
                "role": role,
                "name": f"Synthetic {role.replace('_', ' ').title()} {product[:2].upper()}{n:03d}",
                "minor": role in ("minor_joint_owner", "beneficiary"),
                "document": {
                    "type": rng.choice(["passport", "drivers_license", "state_id"]),
                    "expired": "expired_id" in edge and i == 0,
                },
                "tin_present": not (
                    "minor_without_tin" in edge and role in ("minor_joint_owner", "beneficiary")
                ),
            }
        )
    actor = {
        "case_id": _case_id(product, n),
        "application_type": product,
        "state": state,
        "requested_account": _account_type(product),
        "applicants": applicants,
        "documents_submitted": parties * 2 - (1 if completeness == "incomplete" else 0),
        "address_on_document_matches": "address_mismatch" not in edge,
    }
    reference = {
        "party_count": parties,
        "decision": decision,
        "next_action": next_action,
        "account_type": _account_type(product),
        "roles": roles,
        "eligible": decision != "decline",
        "authorized_signer": "P1",
        "party_separation": parties > 1,
        "exceptions": exceptions,
        "resolution": resolution,
        "state": state,
        "review_due_days": 30 if state in ("NY", "CA") else 45,
        "instrument": "UTMA"
        if product == "custodial"
        else ("joint_tenancy" if parties > 1 else "single_owner"),
    }
    return {
        "case_id": actor["case_id"],
        "application_type": product,
        "completeness": completeness,
        "edge_cases": edge,
        "actor": actor,
        "reference": reference,
    }


def cases(per_product, seed=SEED):
    return [_make_case(p, n, seed) for p in PRODUCTS for n in range(1, per_product + 1)]


def case_catalog(rows):
    by_type = {p: 0 for p in PRODUCTS}
    by_completeness = {c: 0 for c in COMPLETENESS}
    cells = {f"{p}|{c}": 0 for p in PRODUCTS for c in COMPLETENESS}
    edges = {e: 0 for e in EDGE_CASES}
    for row in rows:
        by_type[row["application_type"]] += 1
        by_completeness[row["completeness"]] += 1
        cells[f"{row['application_type']}|{row['completeness']}"] += 1
        for e in row["edge_cases"]:
            edges[e] += 1
    return {
        "dataset": "kyc_cases",
        "generator": GENERATOR,
        "seed": SEED,
        "cases": len(rows),
        "dimensions": {
            "application_type": by_type,
            "completeness": by_completeness,
            "edge_cases": edges,
        },
        "cells": cells,
        "edge_case_rules": EDGE_CASES,
        "minimum_per_application_type": 100,
    }


